"""backend/scripts/dedupe_dataset.py — remove redundant duplicate frames.

WHY
  bulk_harvest.py and seek_harvest.py compare each candidate only against
  the LAST KEPT frame, so they cannot detect a near-copy of something saved
  ten minutes earlier, on a previous run, or by a different pass over the
  same camera. Measured on this dataset:

      5,372 legacy frames -> 1,845 (34%) are duplicate images
        692 deep frames   ->     0 (0%)

  Those 1,845 cost SAHI labelling time and training time while adding no
  gradient: the model already sees an identical image elsewhere in the set.

WHAT IT KEEPS
  One representative per perceptual-hash group. Selection is deliberate,
  not arbitrary:
    1. prefer a deep-harvested frame - it already passed sharpness,
       exposure and learning-value gates
    2. then the sharper image (variance of Laplacian)
    3. then the larger file, as a weak proxy for detail retained
  So the copy that survives is the best copy, not merely the first one
  encountered.

SAFETY
  * --dry-run by default. Nothing is deleted without --apply.
  * --apply MOVES files into data/detection_train/_duplicates/ rather than
    deleting them, so the decision is reversible.
  * Never touches images/train or images/val - those are generated by
    autolabel_frames.py from the camera folders and are rebuilt anyway.

USAGE
  python -m backend.scripts.dedupe_dataset
  python -m backend.scripts.dedupe_dataset --apply
"""
from __future__ import annotations

import argparse
import shutil
from collections import defaultdict
from pathlib import Path

import cv2

ROOT = Path("data/detection_train/images")
QUARANTINE = Path("data/detection_train/_duplicates")


def dhash(img, size: int = 8) -> int:
    g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    g = cv2.resize(g, (size + 1, size), interpolation=cv2.INTER_AREA)
    diff = g[:, 1:] > g[:, :-1]
    out = 0
    for bit in diff.flatten():
        out = (out << 1) | int(bit)
    return out


def sharpness(img) -> float:
    return float(cv2.Laplacian(cv2.cvtColor(img, cv2.COLOR_BGR2GRAY),
                               cv2.CV_64F).var())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apply", action="store_true",
                    help="Move duplicates to the quarantine folder. Without "
                         "this the script only reports.")
    args = ap.parse_args()

    files = [p for p in ROOT.rglob("*.jpg")
             if "train" not in p.parts and "val" not in p.parts]
    print(f"scanning {len(files)} frame(s)...\n")

    groups: dict[int, list[tuple[Path, float, int]]] = defaultdict(list)
    unreadable = 0
    for i, p in enumerate(files, 1):
        img = cv2.imread(str(p))
        if img is None:
            unreadable += 1
            continue
        groups[dhash(img)].append((p, sharpness(img), p.stat().st_size))
        if i % 1000 == 0:
            print(f"  hashed {i}/{len(files)}", flush=True)

    def rank(entry):
        path, sharp, size = entry
        # Sort key: deep frames first, then sharper, then larger.
        return (0 if "_deep" in path.name else 1, -sharp, -size)

    to_remove: list[Path] = []
    per_camera_removed: dict[str, int] = defaultdict(int)
    for h, entries in groups.items():
        if len(entries) < 2:
            continue
        entries.sort(key=rank)
        for path, _, _ in entries[1:]:
            to_remove.append(path)
            per_camera_removed[path.parent.name] += 1

    keep = len(files) - len(to_remove) - unreadable
    print(f"\ndistinct images     : {len(groups)}")
    print(f"redundant duplicates: {len(to_remove)}")
    if unreadable:
        print(f"unreadable (skipped): {unreadable}")
    print(f"would keep          : {keep}")

    if per_camera_removed:
        print("\nduplicates by camera:")
        for cam, n in sorted(per_camera_removed.items(), key=lambda kv: -kv[1])[:15]:
            print(f"  {cam:<10} {n}")

    deep_removed = sum(1 for p in to_remove if "_deep" in p.name)
    print(f"\ndeep-harvested frames in the removal set: {deep_removed}")
    if deep_removed:
        print("  (expected 0 - deep frames were already checked for "
              "uniqueness; investigate before applying)")

    if not args.apply:
        print("\nDRY RUN - nothing changed. Re-run with --apply to quarantine.")
        return

    QUARANTINE.mkdir(parents=True, exist_ok=True)
    moved = failed = 0
    for p in to_remove:
        dst = QUARANTINE / p.parent.name / p.name
        dst.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.move(str(p), str(dst))
            moved += 1
        except OSError as exc:
            print(f"  could not move {p.name}: {exc}")
            failed += 1

    remaining = sum(1 for p in ROOT.rglob("*.jpg")
                    if "train" not in p.parts and "val" not in p.parts)
    print(f"\nmoved {moved} duplicate(s) -> {QUARANTINE}/")
    if failed:
        print(f"{failed} could not be moved")
    print(f"dataset now: {remaining} distinct frame(s)")
    print("\nDuplicates are quarantined, not deleted - delete the folder once "
          "you are satisfied.")
    print("Next: re-run autolabel_frames + train_detector on the cleaned set.")


if __name__ == "__main__":
    main()
